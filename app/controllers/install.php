function seed_cities(): void
{
    $ins = db()->prepare('INSERT INTO cities (name_ku, name_ar, name_en, slug) VALUES (?,?,?,?)
        ON CONFLICT(slug) DO UPDATE SET name_ku = excluded.name_ku, name_ar = excluded.name_ar');
    foreach (KURDISTAN_CITIES as [$ku, $ar, $en]) {
        $ins->execute([$ku, $ar, $en, trim((string) preg_replace('/[^a-z0-9]+/', '-', strtolower($en)), '-')]);
    }
}

function admin_exists(): bool
{
    static $yes = false;
    if ($yes) {
        return true;
    }
    return $yes = (bool) db()->query("SELECT 1 FROM users WHERE role = 'admin' LIMIT 1")->fetchColumn();
}

/** Merge settings into data/config.local.php (atomic write). */
function save_local_config(array $changes): bool
{
    $file = (string) config('local_config_file');
    $cur = is_file($file) ? (array) (require $file) : [];
    $new = array_merge($cur, $changes);
    $tmp = $file . '.' . bin2hex(random_bytes(4));
    $php = "<?php\n// Generated by the Aqarat installer. Safe to edit.\nreturn " . var_export($new, true) . ";\n";
    if (@file_put_contents($tmp, $php, LOCK_EX) === false) {
        return false;
    }
    @chmod($tmp, 0640);
    if (!@rename($tmp, $file)) {
        @unlink($tmp);
        return false;
    }
    if (function_exists('opcache_invalidate')) {
        @opcache_invalidate($file, true);
    }
    return true;
}

function install_checks(): array
{
    $https = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') || in_array($_SERVER['HTTP_HOST'] ?? '', ['localhost', '127.0.0.1'], true)
        || str_starts_with((string) ($_SERVER['HTTP_HOST'] ?? ''), 'localhost:') || str_starts_with((string) ($_SERVER['HTTP_HOST'] ?? ''), '127.0.0.1:');
    $ini = static function (string $k): int {
        $v = trim((string) ini_get($k));
        $n = (int) $v;
        return match (strtolower(substr($v, -1))) { 'g' => $n * 1024, 'm' => $n, 'k' => (int) ($n / 1024), default => (int) ($n / 1048576) };
    };
    return [
        // [label, ok, required, hint]
        ['PHP 8.1+ (' . PHP_VERSION . ')', PHP_VERSION_ID >= 80100, true, t('chk_php')],
        ['SQLite (WAL: ' . db()->query('PRAGMA journal_mode')->fetchColumn() . ')', strtolower((string) db()->query('PRAGMA journal_mode')->fetchColumn()) === 'wal', true, t('chk_sqlite')],
        ['GD + WebP', function_exists('imagewebp'), true, t('chk_gd')],
        ['fileinfo', class_exists('finfo'), true, t('chk_fileinfo')],
        ['OpenSSL + cURL (push)', function_exists('openssl_pkey_derive') && function_exists('curl_multi_init'), false, t('chk_push')],
        [t('chk_writable'), is_writable(dirname((string) config('db_path'))) && is_writable((string) config('upload_dir')), true, t('chk_writable_hint')],
        ['HTTPS', $https, false, t('chk_https')],
        ['upload_max_filesize ≥ 60M (' . ini_get('upload_max_filesize') . ')', $ini('upload_max_filesize') >= 60, false, t('chk_upload')],
    ];
}

function install_form(): void
{
    if (admin_exists()) {
        abort(404);
    }
    seed_cities();
    vapid_keys();
    render('install', [
        'pageTitle'  => t('install_heading') . ' — ' . app_name(),
        'checks'     => install_checks(),
        'detected'   => absolute_base_url(),
    ]);
}

function install_submit(): void
{
    if (admin_exists()) {
        abort(404);
    }
    $name = mb_substr(input('name'), 0, 100);
    $email = mb_strtolower(mb_substr(input('email'), 0, 150));
    $phone = mb_substr(convert_arabic_digits(input('phone')), 0, 30);
    $password = (string) ($_POST['password'] ?? '');
    $lang = in_array(input('default_lang'), SUPPORTED_LANGS, true) ? input('default_lang') : 'ckb';
    $rate = max(100, min(100000, (int) input_int('iqd_per_usd', 1450)));
    $demo = !empty($_POST['demo']);
    $errors = [];
    if (mb_strlen($name) < 2) {
        $errors['name'] = t('v_name');
    }
    if (!filter_var($email, FILTER_VALIDATE_EMAIL)) {
        $errors['email'] = t('v_email');
    }
    if ($phone !== '' && !valid_phone($phone)) {
        $errors['phone'] = t('v_phone');
    }
    if (strlen($password) < 10) {
        $errors['password'] = t('v_password_admin');
    }
    foreach (install_checks() as [$label, $ok, $required]) {
        if ($required && !$ok) {
            $errors['checks'] = t('install_fix_first');
        }
    }
    if ($errors) {
        with_old(compact('name', 'email', 'phone') + ['default_lang' => $lang, 'iqd_per_usd' => (string) $rate, 'demo' => $demo ? '1' : ''], $errors);
        redirect(url('install'));
    }

    $pdo = db();
    $pdo->exec('BEGIN IMMEDIATE');
    if ((bool) $pdo->query("SELECT 1 FROM users WHERE role = 'admin' LIMIT 1")->fetchColumn()) {   // two people installing at once
        $pdo->exec('ROLLBACK');
        abort(404);
    }
    seed_cities();
    $pdo->prepare("INSERT INTO users (name, email, phone, password_hash, role) VALUES (?,?,?,?, 'admin')
        ON CONFLICT(email) DO UPDATE SET role = 'admin', password_hash = excluded.password_hash")
        ->execute([$name, $email, $phone, password_hash($password, PASSWORD_DEFAULT)]);
    $stmt = $pdo->prepare('SELECT id FROM users WHERE email = ?');
    $stmt->execute([$email]);
    $id = (int) $stmt->fetchColumn();
    $pdo->exec('COMMIT');

    // Remember detected settings so links in notifications/share images use the real address.
    save_local_config([
        'app_url'      => absolute_base_url(),
        'default_lang' => $lang,
        'iqd_per_usd'  => $rate,
        'push_subject' => 'mailto:' . $email,
        'installed_at' => date('c'),
    ]);
    vapid_keys();

    if ($demo) {
        @set_time_limit(300);
        ignore_user_abort(true);
        require_once dirname(__DIR__) . '/demo.php';
        // The demo generator writes its own temp images (not HTTP uploads); mark them as trusted for this run only.
        if (!defined('AQARAT_SEEDING')) {
            define('AQARAT_SEEDING', true);
        }
        try {
            seed_demo_data($id);
        } catch (Throwable $e) {
            error_log('aqarat demo data: ' . $e->getMessage());
            flash('error', t('demo_failed'));
        }
    }
    setcookie('lang', $lang, ['expires' => time() + 31536000, 'path' => base_path() . '/', 'samesite' => 'Lax', 'httponly' => true]);
    login_user($id);
    flash('success', t('install_done'));
    redirect(url('admin', ['welcome' => 1]));
}
