<h2>ما نجمعه ولماذا</h2>
<ul>
    <li><strong>بيانات الحساب</strong> (الاسم، البريد، الهاتف، تجزئة كلمة المرور، ومفتاح الدخول بخطوتين إن فعّلته) — لتسجيل الدخول ونشر العقارات والتواصل معك بشأنها. يظهر رقم هاتفك على عقاراتك.</li>
    <li><strong>العقارات والصور والفيديوهات</strong> التي ترفعها — لنشرها. تُعاد معالجة الصور وتُحذف منها بيانات الموقع (GPS) والكاميرا.</li>
    <li><strong>الاستفسارات</strong> (الاسم، البريد، الهاتف اختيارياً، الرسالة) — تُرسل إلى المعلن ليرد عليك.</li>
    <li><strong>الإشعارات</strong> — إذا تابعت مكتباً أو حفظت تنبيه بحث، يعطينا متصفحك عنوان إشعارات ومفاتيح. نحفظ المكاتب التي تتابعها وفلاتر تنبيهاتك. لا حاجة لحساب.</li>
    <li><strong>موقعك</strong> — فقط عند الضغط على «بالقرب مني». يُقرّب إلى نحو 100 م ويُستخدم لذلك البحث ولا يُحفظ — إلا داخل تنبيه بحث تختار حفظه.</li>
    <li><strong>أعداد الزيارات</strong> — نعدّ لكل عقار يومياً المشاهدات والنقرات على واتساب والاتصال، كأرقام فقط، ليعرف المكتب أداء عقاره. لا نسجّل من شاهد أو نقر.</li>
    <li><strong>البلاغات</strong> عن العقارات و<strong>البيانات التقنية</strong> (عنوان IP) لمنع إساءة الاستخدام فقط.</li>
</ul>

<h2>أين تُحفظ ولأي مدة</h2>
<p>تُحفظ البيانات على خادم الاستضافة. تُمحى عناوين IP من الاستفسارات والبلاغات بعد 30 يوماً. تُحذف الاستفسارات بعد 24 شهراً، وسجل الإشعارات بعد 12 شهراً، واشتراكات الإشعارات غير النشطة بعد 400 يوم، وسجل نشاط المدير بعد 24 شهراً. تبقى العقارات حتى تحذفها أنت أو المدير. حذف حسابك يحذف عقاراتك وصورك وفيديوهاتك ومكتبك وما حفظته. تُحفظ نسخة احتياطية من قاعدة البيانات كل يوم وتُحذف بعد 7 أيام، لذا قد تبقى المعلومات المحذوفة في نسخة احتياطية حتى 7 أيام.</p>

