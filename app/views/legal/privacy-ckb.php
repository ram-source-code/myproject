<h2>چی کۆدەکەینەوە و بۆچی</h2>
<ul>
    <li><strong>زانیاری هەژمار</strong> (ناو، ئیمەیڵ، مۆبایل، هاشی وشەی نهێنی و، ئەگەر چوونەژوورەوەی دوو هەنگاوی چالاک بکەیت، کلیلە نهێنییەکەی) — بۆ چوونەژوورەوە، بڵاوکردنەوەی موڵک و پەیوەندیکردن پێتەوە. ژمارەی مۆبایلەکەت لەسەر موڵکەکانت پیشان دەدرێت.</li>
    <li><strong>موڵک، وێنە و ڤیدیۆ</strong> کە بار دەکەیت — بۆ بڵاوکردنەوەیان. وێنەکان دووبارە دروست دەکرێنەوە و زانیاری شوێن (GPS) و کامێرایان لێ دەسڕدرێتەوە.</li>
    <li><strong>پرسیارەکان</strong> (ناو، ئیمەیڵ، مۆبایلی ئارەزوومەندانە، نامە) — دەنێردرێن بۆ ڕیکلامکەر بۆ ئەوەی وەڵامت بداتەوە.</li>
    <li><strong>ئاگادارکردنەوەکان</strong> — ئەگەر نوسینگەیەک فۆڵۆ بکەیت یان ئاگادارکردنەوەی گەڕان پاشەکەوت بکەیت، وێبگەڕەکەت ناونیشان و کلیلێکی ئاگادارکردنەوەمان دەداتێ. پاشەکەوتی دەکەین کام نوسینگانەت فۆڵۆ کردووە و فلتەرەکانی ئاگادارکردنەوەکانت. هەژمار پێویست نییە.</li>
    <li><strong>شوێنەکەت</strong> — تەنها کاتێک «نزیک من» دادەگریت. بە نزیکەیی ١٠٠ مەتر خڕ دەکرێتەوە، بۆ ئەو گەڕانە بەکاردێت و پاشەکەوت ناکرێت — تەنها لەناو ئاگادارکردنەوەیەکی گەڕان کە خۆت هەڵیدەبژێریت.</li>
    <li><strong>ژمارەی سەردانەکان</strong> — بۆ هەر موڵکێک ژمارەی بینین و کرتەکانی واتسئاپ و پەیوەندی ڕۆژانە دەژمێرین، تەنها وەک ژمارە، بۆ ئەوەی نوسینگەکە بزانێت موڵکەکەی چۆنە. تۆمار ناکەین کێ بینیویەتی یان کرتەی کردووە.</li>
    <li><strong>ڕاپۆرتەکان</strong> لەسەر موڵکەکان و <strong>زانیاری تەکنیکی</strong> (ناونیشانی IP) تەنها بۆ سنووردارکردنی خراپ بەکارهێنان.</li>
</ul>

<h2>لە کوێ و بۆ چەند پاشەکەوت دەکرێت</h2>
<p>زانیارییەکان لەسەر سێرڤەری هۆستینگەکەمان پاشەکەوت دەکرێن. ناونیشانی IP لەسەر پرسیار و ڕاپۆرتەکان دوای ٣٠ ڕۆژ دەسڕدرێتەوە. پرسیارەکان دوای ٢٤ مانگ، مێژووی ئاگادارکردنەوەکان دوای ١٢ مانگ، بەشداربوونی ناچالاکی ئاگادارکردنەوە دوای ٤٠٠ ڕۆژ و تۆماری کارەکانی بەڕێوەبەر دوای ٢٤ مانگ دەسڕدرێنەوە. موڵکەکان دەمێننەوە تا خۆت یان بەڕێوەبەر دەیانسڕێتەوە. سڕینەوەی هەژمار موڵک، وێنە، ڤیدیۆ، نوسینگە و پاشەکەوتکراوەکانت دەسڕێتەوە. هەموو ڕۆژێک کۆپییەکی یەدەگی بنکەی زانیاری هەڵدەگیرێت و دوای ٧ ڕۆژ دەسڕدرێتەوە، بۆیە زانیاریی سڕاوە دەکرێت تا ٧ ڕۆژ لە کۆپیی یەدەگدا بمێنێت.</p>

<h2>کێی تر زانیاری وەردەگرێت</h2>
<ul>
    <li><strong>خزمەتگوزاری ئاگادارکردنەوەی</strong> وێبگەڕەکەت (Google، Mozilla، Apple یان Microsoft) ئاگادارکردنەوەکان دەگەیەنن. نامەیەکی شاراوە (encrypted) وەردەگرن کە ناتوانن بیخوێننەوە.</li>
