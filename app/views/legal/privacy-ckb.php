    <li><strong>واتسئاپ / تەلەفۆن:</strong> داگرتنی واتسئاپ یان پەیوەندی ئەو ئەپە بە ژمارەی ڕیکلامکەرەوە دەکاتەوە؛ ئەوەی لەوێ دەینێریت لە نێوان تۆ و ئەواندایە.</li>
    <li>زانیاری نافرۆشین و هیچ ڕیکلام یان شوێنکەوتنی ئامار بەکارناهێنین.</li>
</ul>

