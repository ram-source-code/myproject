// icons used from CSS (mask-image) — written as standalone files
$CSS_ICONS = ['check' => 'check', 'alert' => 'circle-alert', 'chevron' => 'chevron-right'];

function svg_inner(string $file): array
{
    $svg = (string) file_get_contents($file);
    $svg = preg_replace('/<!--.*?-->/s', '', $svg);
    preg_match('/viewBox="([^"]+)"/', $svg, $vb);
    preg_match('/<svg[^>]*>(.*)<\/svg>/s', $svg, $m);
    $inner = trim(preg_replace('/\s+/', ' ', $m[1] ?? ''));
    $inner = preg_replace('/<title>.*?<\/title>/', '', $inner);
    return [$vb[1] ?? '0 0 24 24', $inner];
}

$out = "<?php /* GENERATED by bin/build-icons.php — do not edit. Icons: Lucide (ISC) and Simple Icons (CC0), self-hosted. */ ?>\n";
$out .= '<svg xmlns="http://www.w3.org/2000/svg" class="icon-sprite" aria-hidden="true" focusable="false"><defs>' . "\n";
foreach ($MAP as $id => [$pack, $name]) {
    $file = "$root/bin/icon-pack/$pack/$name.svg";
    if (!is_file($file)) { fwrite(STDERR, "missing $file\n"); exit(1); }
    [$vb, $inner] = svg_inner($file);
    // Lucide: stroke icons (styling via CSS so fill can be toggled, e.g. a "saved" heart). Brands: solid fill.
    // No fill attribute on Lucide symbols: fill inherits from the host <svg>, so CSS can switch it (e.g. saved heart).
    $attrs = $pack === 'lucide'
        ? 'stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"'
        : 'fill="currentColor" stroke="none"';
    $out .= "<symbol id=\"i-$id\" viewBox=\"$vb\" $attrs>$inner</symbol>\n";
}
$out .= "</defs></svg>\n";
file_put_contents("$root/app/views/partials/icons.php", $out);

foreach ($CSS_ICONS as $id => $name) {
    [$vb, $inner] = svg_inner("$root/bin/icon-pack/lucide/$name.svg");
    file_put_contents("$root/assets/icons/$id.svg", "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"$vb\" fill=\"none\" stroke=\"#000\" stroke-width=\"2.5\" stroke-linecap=\"round\" stroke-linejoin=\"round\">$inner</svg>\n");
}
echo count($MAP) . " sprite icons, " . count($CSS_ICONS) . " CSS icons written\n";
