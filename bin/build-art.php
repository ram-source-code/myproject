foreach ($houses as $i => [$w, $h]) {
    if ($w === 0) {                                              // the Grand Gate
        $p->rect($x, 120, 16, 48, 'ink');
        $p->rect($x + 36, 120, 16, 48, 'ink');
        $p->line($x + 16, 132, $x + 36, 132, 'ink');
        $p->pointedArch($x + 18, 168, 16, 30, 'ink', 2);
        $p->hatch([[$x + 20, 166], [$x + 20, 150], [$x + 26, 140], [$x + 32, 150], [$x + 32, 166]], 90, 2.6, 'ink', 0.95);
        foreach ([$x + 4, $x + 40] as $tx) {
            $p->roundArch($tx, 134, 8, 9, 'ink');                // tower windows
        }
        $x += 52;
        continue;
    }
    $top = 168 - $h;
    $p->line($x, $top, $x + $w, $top + mt_rand(-1, 1), 'ink');  // parapet
    $p->line($x + $w, $top, $x + $w, 168, 'ink', 1);
    if ($i === 0) {
        $p->line($x, $top, $x, 168, 'ink');
    }
    // false arched windows / doors
    $n = $w > 45 ? 3 : 2;
    $ww = 6;
    for ($k = 0; $k < $n; $k++) {
        $wx = $x + ($w / ($n + 1)) * ($k + 1) - $ww / 2;
        $p->pointedArch($wx, $top + $h * 0.62, $ww, $h * 0.38, 'ink');
    }
    // rounded buttresses (often three per façade)
    if ($i % 3 === 1) {
        foreach ([0.18, 0.5, 0.82] as $f) {
            $bx = $x + $w * $f;
            $p->curve([[$bx - 2.5, 168], [$bx - 2.5, $top + $h * 0.7], [$bx, $top + $h * 0.62], [$bx + 2.5, $top + $h * 0.7], [$bx + 2.5, 168]], 'ink', 1, 0.3);
        }
    }
    // diamond brickwork band
    if ($i % 4 === 3) {
        for ($dx = $x + 5; $dx < $x + $w - 5; $dx += 8) {
            $p->poly([[$dx, $top + 5], [$dx + 3, $top + 2], [$dx + 6, $top + 5], [$dx + 3, $top + 8]], true, 'light', 1);
        }
    }
    $x += $w;
}
