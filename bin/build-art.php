/**
 * Draws the site's hand-drawn illustrations with bin/art/pen.php and writes them as SVG:
 *   app/views/partials/art/*.php   inline SVG (ink follows the theme colour via CSS)
 *   assets/img/kilim.svg           the woven-band ornament (fixed colours, used as a CSS background)
 *
 *   php bin/build-art.php
 *
 * References: Erbil Citadel — an oval tell whose "wall" is a ring of house façades with false arched windows,
 * rounded buttresses and diamond/triangle brickwork, ramps up to the gates (UNESCO 1437). Mudhafaria minaret —
 * octagonal brick base with two tiers of pointed niches, a balcony, a tapering shaft with hazarbaf (criss-cross)
 * brickwork, top lost. Kurdish (Herki) kilims — diamonds, triangles, zigzags, hooked crosses.
 */
if (PHP_SAPI !== 'cli') {
    exit(1);
}
require __DIR__ . '/art/pen.php';
$root = dirname(__DIR__);
@mkdir("$root/app/views/partials/art", 0755, true);
$write = static function (string $name, string $svg) use ($root): void {
    file_put_contents("$root/app/views/partials/art/$name.php", "<?php /* generated by bin/build-art.php — edit the drawing there */ ?>\n" . $svg . "\n");
    echo str_pad($name, 12) . number_format(strlen($svg) / 1024, 1) . " KB\n";
};

/* ───────────── Erbil skyline (hero horizon) ───────────── */
$p = new Pen(1437);
