foreach ([[$mx - 22, 9], [$mx - 7, 14], [$mx + 13, 9]] as [$fx, $fw]) {   // two tiers of pointed niches per face
    $p->pointedArch($fx, 210, $fw - 1, 22, 'ink');
    $p->pointedArch($fx, 242, $fw - 1, 22, 'ink');
}
$p->line($mx - 24, 186, $mx + 24, 186, 'light', 1);              // the inscription band
$p->rect($mx - 30, 168, 60, 8, 'ink');                           // balcony
for ($bx = $mx - 26; $bx < $mx + 28; $bx += 6) {
    $p->line($bx, 170, $bx, 174, 'light', 1);
}
$shaft = [[$mx - 17, 168], [$mx - 12, 62], [$mx - 6, 58], [$mx - 1, 63], [$mx + 4, 57], [$mx + 12, 61], [$mx + 17, 168]];
$p->line($mx - 17, 168, $mx - 12, 62, 'ink');
$p->line($mx + 17, 168, $mx + 12, 61, 'ink');
$p->poly([[$mx - 12, 62], [$mx - 6, 58], [$mx - 1, 63], [$mx + 4, 57], [$mx + 12, 61]], false, 'ink', 1);   // the lost top
$p->hatch($shaft, 58, 11, 'light', 0.75);                         // hazarbaf criss-cross, loosely
$p->hatch($shaft, 122, 11, 'light', 0.75);
// new apartment blocks and a tower crane (Erbil keeps building)
foreach ([[958, 150, 54], [1020, 118, 50], [1078, 168, 62]] as [$bx, $by, $bw]) {
    $p->rect($bx, $by, $bw, $G - $by, 'ink');
    for ($wy = $by + 10; $wy < $G - 14; $wy += 16) {
        for ($wx = $bx + 7; $wx < $bx + $bw - 9; $wx += 13) {
            if (mt_rand(0, 9) > 1) {
                $p->rect($wx, $wy, 6, 8, 'light', 1);
            }
        }
    }
}
$cx = 1166;
$p->line($cx, $G, $cx, 34, 'ink');
$p->line($cx + 8, $G, $cx + 8, 34, 'ink');
for ($cy = 46; $cy < $G - 6; $cy += 14) {
    $p->line($cx, $cy, $cx + 8, $cy + 12, 'light', 1);
}
